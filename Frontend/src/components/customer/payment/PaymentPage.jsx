import { useState } from "react";
import { Link, useNavigate } from "react-router-dom";

import {
  ArrowLeft,
  ShieldCheck,
  CreditCard,
  Smartphone,
  LockKeyhole,
  CheckCircle2,
  AlertCircle,
} from "lucide-react";

import customerApi, {
  toCustomerCartItems,
} from "../../../services/customerApi";

import { currency } from "../../../utils/customerPricing";
import { useCustomer } from "../../../context/CustomerContext";

export default function PaymentPage() {
  const navigate = useNavigate();

  const {
    checkoutDraft,
    setCheckoutDraft,
    refreshOrders,
    refreshLoyalty,
    clearCart,
    notify,
  } = useCustomer();

  const [method, setMethod] = useState("upi");
  const [outcome, setOutcome] = useState("success");

  const [card, setCard] = useState({
    name: "",
    number: "",
    expiry: "",
    cvv: "",
  });

  const [busy, setBusy] = useState(false);

  const [result, setResult] = useState(null);
  const [error, setError] = useState("");

  const [freshQuote, setFreshQuote] = useState(null);

  /*
   * These are stateful checkpoints, not payment references
   * generated by the frontend.
   *
   * paymentReference is always supplied by the backend.
   *
   * idempotencyKey is only used to make intent creation
   * retries return the same backend-created intent.
   */
  const [paymentReference, setPaymentReference] = useState(null);
  const [idempotencyKey, setIdempotencyKey] = useState(null);
  const [paymentConfirmed, setPaymentConfirmed] = useState(false);

  const updateCard = (key, value) => {
    setCard((current) => ({
      ...current,
      [key]: value,
    }));
  };

  const validateCard = () => {
    if (card.name.trim().length < 2) {
      return "Enter the cardholder name.";
    }

    if (!/^(?:\d{4} ?){3}\d{4}$/.test(card.number.trim())) {
      return "Enter a valid 16-digit demo card number.";
    }

    if (!/^(0[1-9]|1[0-2])\/\d{2}$/.test(card.expiry)) {
      return "Enter expiry as MM/YY.";
    }

    if (!/^\d{3,4}$/.test(card.cvv)) {
      return "Enter a 3 or 4 digit CVV.";
    }

    return "";
  };

  /* ======================================================
     PAYMENT HANDLER

     1. Validate cart.
     2. Calculate authoritative quote.
     3. Create mock payment intent.
     4. Confirm mock payment.
     5. Only after SUCCEEDED, finalise the order.
  ====================================================== */

  const pay = async () => {
    if (!checkoutDraft || busy) return;

    setError("");

    if (method === "card") {
      const invalid = validateCard();

      if (invalid) {
        setError(invalid);
        return;
      }
    }

    if (
      !checkoutDraft.outletId ||
      !checkoutDraft.addressId ||
      !checkoutDraft.cart?.length
    ) {
      setError(
        "Your checkout details are incomplete. Return to checkout and review your order.",
      );

      return;
    }

    setBusy(true);

    try {
      const items = toCustomerCartItems(
        checkoutDraft.cart,
      );

      const basePayload = {
        outletId: checkoutDraft.outletId,
        addressId: checkoutDraft.addressId,
        items,
        fulfillmentType: "DELIVERY",
      };

      let activeReference = paymentReference;

      let confirmed = paymentConfirmed;

      /*
       * STEP 1 — VALIDATE THE CART
       *
       * The backend rechecks outlet assignment, stock,
       * current availability, time-based menu, portions
       * and selected add-ons.
       */
      if (!activeReference && !confirmed) {
        const validation = await customerApi.validateCart(
          basePayload,
        );

        if (validation.valid !== true) {
          throw new Error(
            "The backend could not validate your cart.",
          );
        }

        /*
         * STEP 2 — GET THE AUTHORITATIVE QUOTE
         *
         * Do not trust draft.totals or frontend prices.
         */
        const quotePayload = {
          ...basePayload,

          ...(checkoutDraft.couponCode
            ? {
                couponCode: checkoutDraft.couponCode,
              }
            : {}),

          loyaltyPoints: Number(
            checkoutDraft.loyaltyRedeemPoints || 0,
          ),

          instructions: checkoutDraft.instructions || "",
        };

        const quote = await customerApi.quoteCart(
          quotePayload,
        );

        if (quote.valid !== true) {
          throw new Error(
            "The backend did not return a valid checkout quote.",
          );
        }

        setFreshQuote(quote);

        /*
         * Do not silently charge a different amount from
         * the amount the customer reviewed at checkout.
         *
         * Send the customer back to review the latest quote.
         */
        const previouslyShownTotal = Number(
          checkoutDraft.quote?.total,
        );

        const latestTotal = Number(quote.total);

        if (
          !Number.isFinite(previouslyShownTotal) ||
          Math.abs(latestTotal - previouslyShownTotal) > 0.01
        ) {
          setError(
            "Your order total has changed. Return to checkout to review the updated backend quote before paying.",
          );

          return;
        }

        /*
         * STEP 3 — CREATE THE MOCK PAYMENT INTENT
         *
         * The backend creates the payment reference.
         * The frontend sends only the chosen method and
         * checkout details.
         */
        let activeIdempotencyKey = idempotencyKey;

        if (!activeIdempotencyKey) {
          activeIdempotencyKey =
            window.crypto?.randomUUID?.() ||
            `checkout-${Date.now()}`;

          setIdempotencyKey(activeIdempotencyKey);
        }

        const intent = await customerApi.createMockPaymentIntent(
          {
            ...quotePayload,
            method: method.toUpperCase(),
          },
          activeIdempotencyKey,
        );

        activeReference =
          intent.reference || intent.paymentReference;

        if (!activeReference) {
          throw new Error(
            "The backend did not return a payment reference.",
          );
        }

        setPaymentReference(activeReference);
      }

      /*
       * STEP 4 — CONFIRM THE MOCK PAYMENT
       *
       * This endpoint accepts success, failed or cancelled.
       * It returns SUCCEEDED, FAILED or CANCELLED.
       */
      if (!confirmed) {
        const confirmation = await customerApi.confirmMockPayment({
          reference: activeReference,
          outcome,
        });

        setResult(confirmation);

        if (confirmation.status === "FAILED") {
          setPaymentReference(null);
          setIdempotencyKey(null);
          setPaymentConfirmed(false);

          setError(
            "The demo payment failed. Your cart is unchanged. Choose another payment attempt to retry.",
          );

          return;
        }

        if (confirmation.status === "CANCELLED") {
          setPaymentReference(null);
          setIdempotencyKey(null);
          setPaymentConfirmed(false);

          setError(
            "Payment was cancelled. Your cart is unchanged. No paid kitchen order was confirmed.",
          );

          return;
        }

        if (confirmation.status !== "SUCCEEDED") {
          throw new Error(
            "The backend has not confirmed a successful payment. The order will not be finalised.",
          );
        }

        confirmed = true;
        setPaymentConfirmed(true);
      }

      /*
       * STEP 5 — FINALISE THE ORDER
       *
       * This call is reachable only after the backend
       * has returned SUCCEEDED from mock-confirm.
       *
       * The backend verifies the successful payment and
       * returns the existing paid order.
       */
      const order = await customerApi.createOrder({
        paymentReference: activeReference,
      });

      if (!order?.id) {
        throw new Error(
          "Payment succeeded, but the backend did not return the confirmed order.",
        );
      }

      setResult({
        status: "SUCCEEDED",
        orderId: order.id,
      });

      await Promise.all([
        refreshOrders(),
        refreshLoyalty(),
      ]);

      clearCart();
      setCheckoutDraft(null);

      notify("Payment successful. Your order is confirmed.");

      navigate(
        `/customer/order/${encodeURIComponent(order.id)}`,
        {
          state: {
            justPlaced: true,
          },
        },
      );
    } catch (err) {
      /*
       * If payment confirmation already succeeded but
       * order finalisation failed, keep paymentReference
       * and paymentConfirmed.
       *
       * The next button press retries POST /orders only.
       * It does not create a second payment intent or
       * confirm the payment a second time.
       */
      setError(
        err.message || "Payment could not be completed.",
      );
    } finally {
      setBusy(false);
    }
  };

  if (!checkoutDraft) {
    return (
      <div className="cu-page cu-payment-loading">
        <span className="cu-eyebrow">
          SECURE DEMO CHECKOUT
        </span>

        <h1>Checkout details unavailable</h1>

        <p>
          Your temporary checkout draft is no longer available.
          Return to checkout and prepare the order again.
        </p>

        <Link
          to="/customer/checkout"
          className="cu-button"
        >
          Return to checkout
        </Link>
      </div>
    );
  }

  const displayedTotal = Number(
    freshQuote?.total ?? checkoutDraft.quote?.total ?? 0,
  );

  return (
    <div className="cu-page cu-payment-page">
      <Link
        to="/customer/checkout"
        className="cu-back-link"
      >
        <ArrowLeft size={15} /> Back to checkout
      </Link>

      <div className="cu-payment-heading">
        <span className="cu-eyebrow">
          DEVELOPMENT PAYMENT EXPERIENCE
        </span>

        <h1>Choose how to pay.</h1>

        <p>
          This is a simulated transaction. No real payment
          is processed and no card details are stored.
        </p>
      </div>

      <div className="cu-payment-layout">
        <section className="cu-payment-card">
          <div className="cu-payment-methods">
            <button
              className={method === "upi" ? "is-active" : ""}
              onClick={() => setMethod("upi")}
              disabled={paymentConfirmed}
            >
              <Smartphone size={19} />

              <span>
                <strong>UPI</strong>
                <small>Demo UPI flow</small>
              </span>
            </button>

            <button
              className={method === "card" ? "is-active" : ""}
              onClick={() => setMethod("card")}
              disabled={paymentConfirmed}
            >
              <CreditCard size={19} />

              <span>
                <strong>Card</strong>
                <small>Test card details</small>
              </span>
            </button>
          </div>

          {method === "upi" ? (
            <div className="cu-upi-panel">
              <div className="cu-demo-qr">
                <span className="cu-qr-mark">D</span>

                <div className="cu-qr-grid" aria-hidden="true">
                  {Array.from({ length: 49 }, (_, index) => (
                    <i
                      key={index}
                      className={
                        index % 3 === 0 ||
                        index % 7 === 0 ||
                        [0, 1, 2, 7, 14, 21, 28, 35, 42, 43, 44, 48].includes(
                          index,
                        )
                          ? "is-dark"
                          : ""
                      }
                    />
                  ))}
                </div>
              </div>

              <h2>Pay using UPI</h2>
              <p>Demo UPI ID</p>

              <strong className="cu-upi-id">
                dastarkhwan.demo@upi
              </strong>

              <small>
                This QR is decorative and does not initiate
                a real transfer.
              </small>
            </div>
          ) : (
            <div className="cu-card-form">
              <h2>Test card details</h2>

              <label>
                Cardholder name

                <input
                  value={card.name}
                  onChange={(event) =>
                    updateCard("name", event.target.value)
                  }
                  placeholder="Name on card"
                  autoComplete="off"
                  disabled={paymentConfirmed}
                />
              </label>

              <label>
                Card number

                <input
                  value={card.number}
                  onChange={(event) =>
                    updateCard(
                      "number",
                      event.target.value
                        .replace(/[^\d ]/g, "")
                        .slice(0, 19),
                    )
                  }
                  placeholder="4111 1111 1111 1111"
                  inputMode="numeric"
                  autoComplete="off"
                  disabled={paymentConfirmed}
                />
              </label>

              <div>
                <label>
                  Expiry

                  <input
                    value={card.expiry}
                    onChange={(event) =>
                      updateCard(
                        "expiry",
                        event.target.value
                          .replace(/[^\d/]/g, "")
                          .slice(0, 5),
                      )
                    }
                    placeholder="MM/YY"
                    autoComplete="off"
                    disabled={paymentConfirmed}
                  />
                </label>

                <label>
                  CVV

                  <input
                    value={card.cvv}
                    onChange={(event) =>
                      updateCard(
                        "cvv",
                        event.target.value
                          .replace(/\D/g, "")
                          .slice(0, 4),
                      )
                    }
                    placeholder="123"
                    inputMode="numeric"
                    autoComplete="off"
                    disabled={paymentConfirmed}
                  />
                </label>
              </div>

              <small>
                Use dummy details only. Card details are not sent
                to the backend.
              </small>
            </div>
          )}

          <div className="cu-payment-outcome">
            <strong>Choose a demo result</strong>

            <div className="cu-outcome-options">
              <button
                className={
                  outcome === "success" ? "is-selected" : ""
                }
                onClick={() => setOutcome("success")}
                disabled={paymentConfirmed}
              >
                <CheckCircle2 size={15} /> Success
              </button>

              <button
                className={
                  outcome === "failed" ? "is-selected" : ""
                }
                onClick={() => setOutcome("failed")}
                disabled={paymentConfirmed}
              >
                <AlertCircle size={15} /> Failure
              </button>

              <button
                className={
                  outcome === "cancelled" ? "is-selected" : ""
                }
                onClick={() => setOutcome("cancelled")}
                disabled={paymentConfirmed}
              >
                Cancel
              </button>
            </div>
          </div>

          {result && (
            <div className="cu-payment-safe">
              <ShieldCheck size={16} />

              <span>
                Backend payment status: {result.status}
                {result.orderId ? ` · Order ${result.orderId}` : ""}
              </span>
            </div>
          )}

          {error && (
            <div className="cu-payment-error">
              <AlertCircle size={17} />
              <span>{error}</span>
            </div>
          )}

          <button
            className="cu-button cu-button-wide"
            disabled={busy}
            onClick={pay}
          >
            {busy
              ? "Processing…"
              : paymentConfirmed
                ? "Retry order confirmation"
                : paymentReference
                  ? "Confirm mock payment"
                  : `Pay ${currency(displayedTotal)}`}

            <LockKeyhole size={16} />
          </button>

          <div className="cu-payment-safe">
            <ShieldCheck size={16} />

            Mock payment · no real money · no payment credentials retained
          </div>

          {result?.status === "FAILED" ||
          result?.status === "CANCELLED" ? (
            <button
              className="cu-button-secondary cu-button-wide"
              onClick={() => {
                setOutcome("success");
                setError("");
                setResult(null);
                setPaymentReference(null);
                setIdempotencyKey(null);
                setPaymentConfirmed(false);
              }}
            >
              Retry with a new successful demo attempt
            </button>
          ) : null}
        </section>

        <aside className="cu-bill-card cu-payment-bill">
          <span className="cu-eyebrow">PAYMENT SUMMARY</span>

          <h2>{currency(displayedTotal)}</h2>

          <p>
            {checkoutDraft.cart.reduce(
              (sum, line) => sum + line.quantity,
              0,
            )}{" "}
            items from {checkoutDraft.outletName}
          </p>

          <hr />

          <div>
            <span>Deliver to</span>

            <strong>
              {checkoutDraft.address?.type} ·{" "}
              {checkoutDraft.address?.pincode}
            </strong>
          </div>

          <div>
            <span>Recipient</span>

            <strong>
              {checkoutDraft.address?.name}
            </strong>
          </div>

          <div>
            <span>Payment mode</span>

            <strong>{method.toUpperCase()}</strong>
          </div>

          <small>Prices inclusive of GST where indicated by the backend quote.</small>
        </aside>
      </div>
    </div>
  );
}